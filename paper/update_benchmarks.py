"""Refresh manuscript figures and table from saved per-example measurements.

Run with a Python environment containing reportlab. No timings are collected.
"""
import csv
import json
import math
from pathlib import Path
import statistics
from reportlab import rl_config
from reportlab.pdfgen import canvas
from reportlab.lib.colors import HexColor

# Keep compressed PDF streams binary rather than ASCII85-encoded.
rl_config.useA85 = 0

ROOT = Path(__file__).resolve().parents[1]
PAPER = ROOT / 'paper'
SUITES = ('list', 'array', 'array_list', 'hash_map')
LABELS = {
    'list_traverse': 'Linked lists: Traverse',
    'list_build_scan': 'Linked lists: Prepend + scan',
    'array_read': 'Arrays: Indexed read',
    'array_write_read': 'Arrays: Write + read passes',
    'arraylist_read': 'Array lists: Indexed read',
    'arraylist_build_scan': 'Array lists: Append + scan',
    'arraylist_rotate': 'Array lists: Front removal + append',
    'hashmap_build_scan': 'Hash maps: Insert + scan',
    'hashmap_hit': 'Hash maps: Lookup hit',
    'hashmap_miss': 'Hash maps: Lookup miss',
    'hashmap_wide_key': 'Hash maps: Large-key hit',
    'hashmap_collision': 'Hash maps: Capacity-spaced hit',
}
COLORS = {'CJR': HexColor('#176f76'), 'Std': HexColor('#de8b37')}


def load():
    summary, raw = [], []
    for suite in SUITES:
        directory = ROOT / 'example' / suite / 'benchmark/results'
        summary.extend(json.loads((directory / 'summary.json').read_text()))
        with (directory / 'raw.csv').open() as stream:
            raw.extend(csv.DictReader(stream))
    return summary, raw


def paired(raw, case, n):
    values = {}
    for row in raw:
        if row['case'] == case and int(row['n']) == n:
            key = row['process'], row['trial']
            values.setdefault(key, {})[row['implementation']] = float(row['elapsed_ns']) / int(row['operations'])
    ratios = [v['CJR'] / v['Std'] for v in values.values()]
    q1, _, q3 = statistics.quantiles(ratios, n=4, method='inclusive')
    return statistics.median(ratios), q1, q3


def main():
    summary, raw = load()
    # Retain the configured order rather than sorting by timing or case name.
    cases = list(LABELS)
    assert {r['case'] for r in summary} == set(LABELS)
    rows = []
    for case in cases:
        n = max(r['n'] for r in summary if r['case'] == case)
        medians = {r['implementation']: r['median_ns'] for r in summary if r['case'] == case and r['n'] == n}
        rows.append((case, n, medians, paired(raw, case, n)))
    table = ['% Generated by paper/update_benchmarks.py from example/*/benchmark/results/.',
             r'\begin{tabular}{@{}lrrrr@{}}', r'\hline',
             r'Workload & $n$ & CJR (ns) & Std (ns) & Ratio \\', r'\hline']
    for case, n, medians, (ratio, _, _) in rows:
        table.append(f"{LABELS[case]} & {n:,} & {medians['CJR']:.2f} & {medians['Std']:.2f} & {ratio:.3f}" + r' \\')
    table.extend([r'\hline', r'\end{tabular}'])
    (PAPER / 'benchmark-measurements.tex').write_text('\n'.join(table) + '\n')

    out = PAPER / 'figures'; out.mkdir(exist_ok=True)
    c = canvas.Canvas(str(out / 'benchmark-overview.pdf'), pagesize=(720, 400), invariant=1)
    c.setTitle('CJR / standard-library paired time ratios')
    c.setFont('Helvetica-Bold', 13); c.drawString(16, 380, 'CJR / standard-library time at the largest tested size')
    x = lambda value: 280 + (math.log10(value) + 3) / 4 * 390
    bottom, top = 62, 353
    c.setFont('Helvetica', 9)
    for tick in (.001, .01, .1, 1, 10):
        c.setStrokeColor(HexColor('#dddddd')); c.line(x(tick), bottom, x(tick), top)
        c.setFillColor(HexColor('#333333')); c.drawCentredString(x(tick), bottom-16, f'{tick:g}')
    c.setDash(3, 3); c.setStrokeColor(HexColor('#666666')); c.line(x(1), bottom, x(1), top); c.setDash()
    for i, (case, n, _, (ratio, q1, q3)) in enumerate(rows):
        y = top - 13 - i * 23
        c.setFillColor(HexColor('#222222')); c.drawString(16, y-3, LABELS[case])
        c.setStrokeColor(COLORS['CJR']); c.setLineWidth(2); c.line(x(q1), y, x(q3), y)
        c.setFillColor(COLORS['CJR']); c.circle(x(ratio), y, 3, fill=1, stroke=0)
        c.setFillColor(HexColor('#222222')); c.drawRightString(712, y-3, f'{ratio:.3f}')
    c.drawCentredString(475, 28, 'Paired time ratio (log scale; lower is faster)')
    c.setFont('Helvetica', 8); c.drawString(16, 9, 'Hash maps: 16 Oct 2026; other containers: saved 12 Oct 2026 run. Dots: medians; whiskers: IQR.')
    c.save()

    c = canvas.Canvas(str(out / 'benchmark-scaling.pdf'), pagesize=(720, 440), invariant=1)
    c.setTitle('Container benchmark scaling')
    panels = [('arraylist_rotate', 'Array-list front rotation'), ('hashmap_wide_key', 'Hash-map large-key hit'),
              ('hashmap_miss', 'Hash-map miss'), ('hashmap_collision', 'Hash-map capacity-spaced hit')]
    for panel, (case, title) in enumerate(panels):
        left = 58 + (panel % 2) * 355
        bottom = 264 - (panel // 2) * 210
        width, height = 280, 128
        values = [r for r in summary if r['case'] == case]
        ns = sorted({r['n'] for r in values})
        ymin = 10 ** math.floor(math.log10(min(r['q1_ns'] for r in values)))
        ymax = 10 ** math.ceil(math.log10(max(r['q3_ns'] for r in values)))
        xpos = lambda n: left + (math.log(n)-math.log(ns[0]))/(math.log(ns[-1])-math.log(ns[0]))*width
        ypos = lambda t: bottom + (math.log(t)-math.log(ymin))/(math.log(ymax)-math.log(ymin))*height
        c.setFillColor(HexColor('#222222')); c.setFont('Helvetica-Bold', 11); c.drawString(left, bottom+height+18, title)
        c.setFont('Helvetica', 9)
        for exponent in range(round(math.log10(ymin)), round(math.log10(ymax))+1):
            t=10**exponent; y=ypos(t)
            c.setStrokeColor(HexColor('#dddddd')); c.line(left, y, left+width, y)
            c.drawRightString(left-8, y-3, f'{t:g}')
        for n in ns:
            c.drawCentredString(xpos(n), bottom-15, f'{n:,}')
        c.drawCentredString(left+width/2, bottom-30, 'Number of keys / items (log scale)')
        c.saveState(); c.translate(left-37,bottom+height/2); c.rotate(90); c.drawCentredString(0,0,'ns per operation (log scale)'); c.restoreState()
        for impl in COLORS:
            series=sorted((r for r in values if r['implementation']==impl),key=lambda r:r['n'])
            c.setStrokeColor(COLORS[impl]); c.setFillColor(COLORS[impl]); c.setLineWidth(1.5)
            for a,b in zip(series,series[1:]):
                c.line(xpos(a['n']),ypos(a['median_ns']),xpos(b['n']),ypos(b['median_ns']))
            for r in series:
                x,y=xpos(r['n']),ypos(r['median_ns'])
                c.line(x,ypos(r['q1_ns']),x,ypos(r['q3_ns']));c.circle(x,y,2.5,fill=1,stroke=0)
    for i, impl in enumerate(COLORS):
        c.setFillColor(COLORS[impl]);c.circle(290+i*100,20,3,fill=1,stroke=0);c.drawString(300+i*100,17,impl)
    c.save()
    print('Refreshed manuscript benchmark table and two PDF figures from saved measurements.')


if __name__ == '__main__':
    main()
