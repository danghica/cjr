(** Bounds for every generated byte offset and the mutable IGE counter. *)
From Coq Require Import ZArith Lia.
From cjr.aes_ige Require Import bytes.
Open Scope Z_scope.
Definition int64_max := 9223372036854775807.
Theorem schedule_offset_bounds nr r j :
 (nr = 10 \/ nr = 12 \/ nr = 14) -> 0 <= r <= nr -> 0 <= j < 16 ->
 0 <= 16*r+j < 240 /\ 16*r+j <= int64_max.
Proof. unfold int64_max; lia. Qed.
Theorem expansion_offset_bounds i j : (i < 60)%nat -> 0 <= j < 4 ->
 0 <= 4*Z.of_nat i+j < 240 /\ 4*Z.of_nat i+j <= int64_max.
Proof. unfold int64_max; lia. Qed.
Theorem expansion_predecessor_bounds nk i :
 (nk=4 \/ nk=6 \/ nk=8)%nat -> (nk <= i < 60)%nat ->
 (i-nk < i /\ i-1 < i /\ i-nk < 60 /\ i-1 < 60)%nat.
Proof. lia. Qed.
Theorem workspace_offset_bounds part j :
 (part=0 \/ part=16 \/ part=32 \/ part=48) -> 0 <= j < 16 ->
 0 <= part+j < 64 /\ part+j <= int64_max.
Proof. unfold int64_max; lia. Qed.
Theorem iv_offset_bounds part j : (part=0 \/ part=16) -> 0 <= j < 16 ->
 0 <= part+j < 32 /\ part+j <= int64_max.
Proof. unfold int64_max; lia. Qed.
Theorem ige_index_bounds i n j :
 0 <= i -> 0 <= n <= int64_max -> i <= n-16 -> 0 <= j < 16 ->
 0 <= i+j < n /\ 0 <= i+16 <= n /\
 -9223372036854775808 <= n-16 <= int64_max.
Proof. unfold int64_max in *; lia. Qed.
